def translate(text: str) -> str:
    # "Bloc" -> "Block" first, so that the longer phrases below can refer to "Block N"
    text = text.replace("BLOC ", "BLOCK ").replace("Bloc ", "Block ")
    for fr, en in PAIRS:
        text = text.replace(fr, en)
    return text
